#Data Scaling Function
def fun_scale_vectorized(chunk):
    """
    Vectorized scaling of the input chunk data to a range between 0 and 1 for all channels.

    Parameters:
    chunk (numpy.ndarray): A 2D array representing a chunk of data across multiple channels.

    Returns:
    numpy.ndarray: The scaled chunk data.
    """
    # Compute min values across the time dimension for each channel
    min_vals = np.min(chunk, axis=0)
    # Explanation:
    # - 'np.min(chunk, axis=0)' calculates the minimum value for each channel across all time steps.
    # - This identifies the lowest value in each channel, which is essential for scaling.
    # - Ensures that scaling is done relative to the data's actual range.
    # Reference: https://numpy.org/doc/stable/reference/generated/numpy.min.html

    # Compute max values across the time dimension for each channel
    max_vals = np.max(chunk, axis=0)
    # Explanation:
    # - 'np.max(chunk, axis=0)' calculates the maximum value for each channel across all time steps.
    # - Identifies the highest value in each channel, necessary for determining the scaling range.
    # - Ensures that scaling accounts for the full range of data in each channel.
    # Learn more about numpy.max: https://numpy.org/doc/stable/reference/generated/numpy.max.html

    # Perform min-max scaling vectorized for all channels
    scaled_chunk = (chunk - min_vals) / (max_vals - min_vals + 1e-8)
    # Explanation:
    # - Min-max scaling transforms data to a fixed range, typically [0, 1].
    # - '(chunk - min_vals)' shifts the data so that the minimum value in each channel becomes 0.
    # - '(max_vals - min_vals)' computes the range of each channel.
    # - Dividing by the range scales the data to [0, 1].
    # - Adding a small epsilon (1e-8) prevents division by zero in case 'max_vals' equals 'min_vals'.
    # - This vectorized operation efficiently scales all channels simultaneously without explicit loops.
    # Learn more about min-max scaling: https://en.wikipedia.org/wiki/Feature_scaling#Rescaling_(min-max_normalization)

    return scaled_chunk
    # Explanation:
    # - Returns the scaled chunk data as a NumPy array.
    # - The output has the same shape as the input, with values scaled between 0 and 1 for each channel.
    # - Ensures that the data is normalized, which can improve model training stability and performance.
    # Reference: https://numpy.org/doc/stable/user/quickstart.html#the-basics

# Define a generator function to create data chunks from CSV files
def generate_chunks(files, label):
    """
    Generates scaled and reshaped data chunks from a list of CSV files.

    Parameters:
    files (list of str): List of file paths to CSV files.
    label (int): Label associated with the data (e.g., 0 for normal, 1 for abnormal).

    Yields:
    tuple: A tuple containing a data chunk as a float32 tensor and its corresponding label as an int32.
    """
    # Iterate over each file in the provided list
    for file in files:
        # Read the CSV file into a pandas DataFrame with float32 dtype to reduce memory usage
        data = pd.read_csv(file, dtype='float32')
        # Explanation:
        # - pd.read_csv reads a CSV file into a DataFrame.
        # - Setting dtype='float32' ensures that all numerical data is stored in 32-bit floating point format,
        #   which conserves memory compared to the default float64.

        # Extract the header (column names), convert them to float32, and reshape to a 2D array with one row
        header = np.array([float(val) for val in data.columns.values], dtype='float32').reshape(1, -1)
        # Explanation:
        # - data.columns.values retrieves the column names from the DataFrame.
        # - The list comprehension converts each column name to a float.
        # - np.array creates a NumPy array from the list, specifying dtype='float32'.
        # - reshape(1, -1) transforms the array into a 2D array with one row and as many columns as needed.

        # Concatenate the header with the data values along the first axis (rows)
        data_array = np.concatenate([header, data.values], axis=0).astype('float32')
        # Explanation:
        # - data.values converts the DataFrame into a NumPy array.
        # - np.concatenate combines the header and data arrays vertically (along rows).
        # - astype('float32') ensures the combined array has float32 data type.

        # Assign the concatenated array to 'signal' for further processing
        signal = data_array
        # Explanation:
        # - 'signal' now contains both the header and the data from the CSV file, ready for chunking and scaling.

        # Initialize the starting index for chunking
        start = 0
        # Explanation:
        # - 'start' marks the beginning of the current chunk within the signal.

        # Loop to create chunks as long as there's enough data left
        while start + window_size <= len(signal):
            # Define the end index of the current chunk
            end = start + window_size
            # Explanation:
            # - 'window_size' determines the number of data points in each chunk.
            # - 'end' marks the end of the current chunk.

            # Extract the chunk of data from 'start' to 'end'
            chunk = signal[start:end, :]
            # Explanation:
            # - Slices the 'signal' array to obtain a subset of data points for the current chunk.
            # - ':' indicates that all channels are included.

            # Vectorized scaling of the chunk across all channels
            chunk = fun_scale_vectorized(chunk)
            # Explanation:
            # - Applies the previously defined scaling function to normalize the chunk's data to [0, 1].

            # Reshape the chunk to a 3D array suitable for machine learning models
            # Assuming window_size is a perfect square, reshape to (sqrt(window_size), sqrt(window_size), num_channels)
            chunk = chunk.reshape(int(np.sqrt(chunk.shape[0])), int(np.sqrt(chunk.shape[0])), num_channels)
            # Explanation:
            # - Reshaping is necessary to format the data correctly for input into machine learning models, such as Convolutional Neural Networks (CNNs).
            # - The code assumes that 'window_size' is a perfect square (e.g., 1024 = 32x32).
            # - 'num_channels' represents the number of data channels (features) per data point.
            # - The resulting shape is (height, width, channels).

            # Yield the processed chunk and its corresponding label
            yield (chunk.astype('float32'), label)
            # Explanation:
            # - 'yield' makes this function a generator, producing one chunk-label pair at a time.
            # - 'chunk.astype('float32')' ensures the data is in float32 format, compatible with TensorFlow.

            # Move the 'start' index forward to the next position, allowing for overlap between chunks
            start += (window_size - overlap)
            # Explanation:
            # - 'overlap' determines how much consecutive chunks overlap with each other.
            # - For example, with window_size=100 and overlap=50, chunks will be [0-100], [50-150], [100-200], etc.
            # - This overlapping can help models learn temporal dependencies better.

