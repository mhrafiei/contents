# Function to define callbacks for training
def fun_model_callbacks():
    """
    Defines and returns a list of Keras callbacks to be used during model training.

    Returns:
    list: A list containing EarlyStopping and ReduceLROnPlateau callbacks.
    """
    # Early stopping callback to stop training when validation loss doesn't improve
    cb_early_stopping = tf.keras.callbacks.EarlyStopping(
        monitor='val_loss',            # Metric to monitor for improvement
        patience=3,                    # Number of epochs with no improvement after which training will be stopped
        restore_best_weights=True      # Restores model weights from the epoch with the best value of the monitored metric
    )
    # Explanation:
    # - **EarlyStopping:** Prevents overfitting by halting training when the model's performance on the validation set stops improving.
    # - **Monitor:** 'val_loss' is a common choice as it reflects the model's generalization ability.
    # - **Patience:** Allows the model some epochs to improve before stopping, accommodating minor fluctuations.
    # - **Restore Best Weights:** Ensures that the model retains the best-performing weights, not the weights from the final epoch.
    # Learn more about EarlyStopping: https://keras.io/api/callbacks/early_stopping/

    # Reduce learning rate callback when validation loss plateaus
    cb_reduce_lr = tf.keras.callbacks.ReduceLROnPlateau(
        monitor='val_loss',            # Metric to monitor for improvement
        factor=0.5,                    # Factor by which the learning rate will be reduced
        patience=2,                    # Number of epochs with no improvement after which learning rate will be reduced
        min_lr=0.00001                 # Lower bound on the learning rate
    )
    # Explanation:
    # - **ReduceLROnPlateau:** Dynamically adjusts the learning rate when the model's performance stagnates.
    # - **Factor:** Determines how much the learning rate is reduced. Here, it halves the learning rate.
    # - **Patience:** After 2 epochs without improvement, the learning rate is reduced.
    # - **min_lr:** Ensures that the learning rate does not become too small, which could hinder further learning.
    # Learn more about ReduceLROnPlateau: https://keras.io/api/callbacks/reduce_lr_on_plateau/

    return [cb_early_stopping, cb_reduce_lr]
    # Returns a list of the defined callbacks, which can be passed to the `model.fit` method during training
    # Learn more about Keras callbacks: https://keras.io/api/callbacks/

# Function to train the model with given dataset, epochs, and callbacks
def fun_model_train(model, dataset_tr, dataset_vl, epochs, callbacks, steps_per_epoch_tr, steps_per_epoch_vl, validation_batch_size):
    """
    Trains the given Keras model using the provided training and validation datasets.

    Parameters:
    model (tf.keras.Model): The Keras model to train.
    dataset_tr (tf.data.Dataset): The training dataset.
    dataset_vl (tf.data.Dataset): The validation dataset.
    epochs (int): Number of epochs to train the model.
    callbacks (list): List of Keras callbacks to apply during training.
    steps_per_epoch_tr (int): Number of training steps per epoch.
    steps_per_epoch_vl (int): Number of validation steps per epoch.
    validation_batch_size (int): Batch size for validation data.

    Returns:
    tf.keras.Model: The trained Keras model.
    """
    # Initiates the training process using the fit method
    model.fit(
        dataset_tr,                              # Training data
        epochs=epochs,                           # Total number of epochs to train
        verbose=1,                               # Verbosity mode: 0 = silent, 1 = progress bar, 2 = one line per epoch
        shuffle=True,                            # Whether to shuffle the training data before each epoch
        validation_data=dataset_vl,              # Validation data to evaluate the model at the end of each epoch
        validation_batch_size=validation_batch_size,  # Batch size for validation data
        steps_per_epoch=steps_per_epoch_tr,      # Total number of steps (batches of samples) before declaring one epoch finished
        validation_steps=steps_per_epoch_vl,     # Total number of steps (batches of samples) to validate after each epoch
        callbacks=callbacks                      # List of callback functions to apply during training
    )
    # Explanation:
    # - **dataset_tr:** The training dataset provides input data and labels for the model to learn from.
    # - **epochs:** Determines how many times the entire training dataset is passed through the model.
    # - **verbose:** Controls the amount of logging during training. '1' provides a progress bar with metrics.
    # - **shuffle:** Shuffling the training data each epoch helps prevent the model from learning the order of the data, promoting better generalization.
    # - **validation_data:** Enables evaluation of the model on unseen data at the end of each epoch, providing insight into overfitting and generalization.
    # - **validation_batch_size:** Defines how many samples per validation step. Adjusting this can balance memory usage and speed.
    # - **steps_per_epoch_tr & steps_per_epoch_vl:** Define how many batches are processed in each epoch for training and validation, respectively.
    # - **callbacks:** Incorporates mechanisms like early stopping and learning rate adjustments to enhance training efficiency and performance.
    # Learn more about model.fit: https://keras.io/api/models/model_training_apis/#fit-method

    return model
    # Returns the trained model, which can be further evaluated or used for predictions

# Function to evaluate the model with a given dataset
def fun_model_evaluate(model, data, steps):
    """
    Evaluates the given Keras model on the provided dataset.

    Parameters:
    model (tf.keras.Model): The Keras model to evaluate.
    data (tf.data.Dataset): The dataset to evaluate the model on.
    steps (int): Number of steps (batches of samples) to evaluate.

    Returns:
    list: A list containing the evaluation metric(s), e.g., accuracy.
    """
    # Evaluates the model on the provided dataset
    _, acc = model.evaluate(
        data,           # Dataset to evaluate
        steps=steps,    # Number of steps (batches) to evaluate
        verbose=1        # Verbosity mode: 0 = silent, 1 = progress bar, 2 = one line per epoch, 3 = one line per batch (if supported)
    )
    # Explanation:
    # - `model.evaluate` computes the loss and specified metrics on the provided dataset.
    # - The underscore `_` captures the loss value, while `acc` captures the accuracy metric.
    # - **Verbosity 3:** Typically not standard; TensorFlow usually supports 0, 1, or 2. If 3 is unsupported, it defaults to a lower verbosity level.
    # - Ensures that the evaluation is performed over a specified number of steps to handle large datasets efficiently.
    # Learn more about model.evaluate: https://keras.io/api/models/model_training_apis/#evaluate-method

    return [acc]
    # Returns the accuracy as a list. This can be extended to include other metrics if needed.

