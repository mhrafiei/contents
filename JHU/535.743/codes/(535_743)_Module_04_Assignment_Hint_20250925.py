# Function to serialize a single example
def serialize_example(feature, label):
    """
    Serializes a single feature-label pair into a TFRecord Example.

    Parameters:
        feature (tf.Tensor): The feature tensor to serialize.
        label (tf.Tensor): The label tensor to serialize.

    Returns:
        bytes: The serialized Example as a string.
    """
    # Serialize the feature tensor to a string
    feature_serialized = tf.io.serialize_tensor(feature)
    # Explanation:
    # - 'tf.io.serialize_tensor' converts the tensor into a serialized string representation.
    # - This is necessary for storing tensors in TFRecord files, which require binary data.
    # - Ensures that the tensor can be efficiently written to disk and later reconstructed.
    # Learn more about tensor serialization: https://www.tensorflow.org/api_docs/python/tf/io/serialize_tensor

    # Serialize the label tensor to a string
    label_serialized = tf.io.serialize_tensor(label)
    # Explanation:
    # - Similar to 'feature_serialized', this line serializes the label tensor.
    # - Consistent serialization ensures that both features and labels can be stored together in the same Example.
    # Reference: https://www.tensorflow.org/api_docs/python/tf/io/serialize_tensor

    # Create a dictionary mapping feature names to tf.train.Feature
    feature_dict = {
        'feature': tf.train.Feature(bytes_list=tf.train.BytesList(value=[feature_serialized.numpy()])),
        'label': tf.train.Feature(bytes_list=tf.train.BytesList(value=[label_serialized.numpy()])),
    }
    # Explanation:
    # - Constructs a dictionary where each key corresponds to a feature in the Example.
    # - 'tf.train.Feature' is used to define the type of each feature; in this case, both are byte strings.
    # - 'bytes_list' is appropriate for serialized tensors, which are stored as byte strings.
    # - 'feature_serialized.numpy()' converts the serialized tensor from a TensorFlow tensor to a NumPy array, which is then converted to bytes.
    # - This structure is required by the TFRecord format to store complex data types.
    # Learn more about tf.train.Feature: https://www.tensorflow.org/api_docs/python/tf/train/Feature

    # Create a tf.train.Example message using the feature dictionary
    example_proto = tf.train.Example(features=tf.train.Features(feature=feature_dict))
    # Explanation:
    # - 'tf.train.Example' is a protocol buffer used to serialize data for TensorFlow.
    # - It contains a 'Features' message, which holds the actual data in the form of a feature dictionary.
    # - This structure allows for flexible and efficient storage of complex data types.
    # - Essential for creating TFRecord files that can be efficiently read during training.
    # Reference: https://www.tensorflow.org/api_docs/python/tf/train/Example

    # Serialize the Example protocol buffer to a string
    return example_proto.SerializeToString()
    # Explanation:
    # - 'SerializeToString()' converts the Example protocol buffer into a serialized string.
    # - This serialized string can be written directly to a TFRecord file.
    # - Ensures that the Example is stored in a compact binary format suitable for high-performance I/O operations.
    # Learn more about serialization: https://developers.google.com/protocol-buffers/docs/encoding

# Function to process and serialize the dataset
def write_dataset_to_tfrecord(dataset, tfrecord_file):
    """
    Writes a TensorFlow Dataset to a TFRecord file by serializing each example.

    Parameters:
        dataset (tf.data.Dataset): The dataset to serialize and write.
        tfrecord_file (str): The path to the output TFRecord file.
    """
    # Open a TFRecordWriter to write the serialized examples
    with tf.io.TFRecordWriter(tfrecord_file) as writer:
        # Explanation:
        # - 'tf.io.TFRecordWriter' is used to write serialized Example protocol buffers to a TFRecord file.
        # - It handles the low-level file I/O operations, ensuring data is written in the correct format.
        # - Efficient for writing large datasets as it supports streaming data to disk.
        # Learn more about TFRecordWriter: https://www.tensorflow.org/api_docs/python/tf/io/TFRecordWriter

        # Iterate over each feature-label pair in the dataset
        for feature, label in dataset:
            # Serialize the current example
            serialized_example = serialize_example(feature, label)
            # Explanation:
            # - Calls the 'serialize_example' function to convert the feature-label pair into a serialized Example.
            # - Ensures that each example is properly formatted before writing to the TFRecord file.
            # - Maintains consistency in data formatting across all examples.
            # Reference: https://www.tensorflow.org/api_docs/python/tf/io/serialize_tensor

            # Write the serialized example to the TFRecord file
            writer.write(serialized_example)
            # Explanation:
            # - Writes the serialized Example string to the TFRecord file.
            # - Appends each example sequentially, building the complete dataset in binary format.
            # - Enables efficient reading and parsing during training.
            # Learn more about writing TFRecords: https://www.tensorflow.org/tutorials/load_data/tfrecord#writing_tfrecord_files

# Function to parse a single serialized example
def parse_example(serialized_example):
    """
    Parses a single serialized TFRecord Example into feature and label tensors.

    Parameters:
        serialized_example (tf.Tensor): A scalar string Tensor; a single serialized Example.

    Returns:
        tuple: A tuple containing the feature tensor and the label tensor.
    """
    # Define the feature description for parsing
    feature_description = {
        'feature': tf.io.FixedLenFeature([], tf.string),
        'label': tf.io.FixedLenFeature([], tf.string),
    }
    # Explanation:
    # - 'feature_description' specifies the expected structure of the serialized Example.
    # - 'tf.io.FixedLenFeature' is used for features with a fixed length; here, both 'feature' and 'label' are scalar strings.
    # - This description guides TensorFlow on how to parse the serialized data correctly.
    # - Essential for accurate deserialization of TFRecord data.
    # Learn more about feature descriptions: https://www.tensorflow.org/api_docs/python/tf/io/parse_single_example

    # Parse the serialized Example using the feature description
    example = tf.io.parse_single_example(serialized_example, feature_description)
    # Explanation:
    # - 'tf.io.parse_single_example' parses a single serialized Example proto.
    # - Returns a dictionary mapping feature names to TensorFlow tensors.
    # - Converts the binary data back into usable tensors for model input.
    # - Ensures that the data is correctly interpreted according to the feature description.
    # - Facilitates the reconstruction of the original feature and label tensors.
    # Learn more about tf.io.parse_single_example: https://www.tensorflow.org/api_docs/python/tf/io/parse_single_example

    # Deserialize the feature tensor from the parsed Example
    feature = tf.io.parse_tensor(example['feature'], out_type=tf.float32)
    # Explanation:
    # - 'tf.io.parse_tensor' deserializes the byte string back into a TensorFlow tensor of the specified type.
    # - 'out_type=tf.float32' ensures that the feature tensor is converted to float32, matching the original data type.
    # - Maintains consistency between serialized and deserialized data types.
    # - Facilitates the reconstruction of the original feature tensor for model input.
    # Learn more about parse_tensor: https://www.tensorflow.org/api_docs/python/tf/io/parse_tensor

    # Deserialize the label tensor from the parsed Example
    label = tf.io.parse_tensor(example['label'], out_type=tf.int32)
    # Explanation:
    # - Similar to the feature tensor, this line deserializes the label tensor.
    # - 'out_type=tf.int32' ensures that the label tensor is converted to int32, matching the original data type.
    # - Ensures that labels are correctly interpreted for loss calculation and model evaluation.
    # Reference: https://www.tensorflow.org/api_docs/python/tf/io/parse_tensor

    # Explicitly set the shape of the feature tensor
    feature.set_shape([res, res, num_channels])  # e.g., [32, 32, 8]
    # Explanation:
    # - 'feature.set_shape' explicitly defines the shape of the feature tensor.
    # - Ensures that TensorFlow knows the exact dimensions of the tensor, which is necessary for model compatibility.
    # - Helps TensorFlow optimize the computation graph by knowing tensor shapes in advance.
    # - Prevents shape-related errors during model training and inference.
    # Reference: https://www.tensorflow.org/api_docs/python/tf/Tensor#set_shape

    # Explicitly set the shape of the label tensor
    label.set_shape([])  # Scalar label
    # Explanation:
    # - 'label.set_shape' explicitly defines the shape of the label tensor as a scalar.
    # - Ensures that TensorFlow treats the label as a single integer value, suitable for classification tasks.
    # - Maintains consistency between serialized and deserialized label shapes.
    # - Prevents shape-related errors during loss calculation and metric evaluation.
    # Learn more about tensor shapes: https://www.tensorflow.org/guide/tensor

    return feature, label
    # Explanation:
    # - Returns a tuple containing the deserialized and reshaped feature tensor and label tensor.
    # - These tensors are ready to be used as inputs and targets in the training and evaluation pipelines.
    # - Facilitates seamless integration with TensorFlow's data processing and model training workflows.
    # Reference: https://www.tensorflow.org/guide/data

# Function to load tfrecord files
def load_tfrecords(tfrecord_file):
    # Create a dataset from the TFRecord file using TensorFlow's TFRecordDataset.
    # TFRecordDataset is an efficient data loader for large datasets stored in TFRecord format.
    # It allows for fast data streaming and is optimized for performance in TensorFlow.
    # Learn more: https://www.tensorflow.org/api_docs/python/tf/data/TFRecordDataset
    tfrecord_dataset = tf.data.TFRecordDataset(tfrecord_file)
    # Parse the serialized data in the TFRecord file by mapping each serialized example to a parsed example.
    # The 'parse_example' function should define how to decode the serialized data into usable tensors.
    # This step is crucial for converting raw data into a format suitable for model training.
    # Learn more about parsing TFRecords: https://www.tensorflow.org/tutorials/load_data/tfrecord
    return tfrecord_dataset.map(parse_example)

